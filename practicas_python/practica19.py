# Actividad 19: Mensaje de bienvenida con función
# Define una función que muestre un mensaje de bienvenida decorado.

# Defino una función llamada 'mostrar_bienvenida'
# Esta función no recibe parámetros (los paréntesis están vacíos)
def mostrar_bienvenida():
    # Imprimo una línea de signos iguales
    # La expresión "=" * 50 repite el signo = 50 veces
    print("=" * 50)
    
    # Muestro el primer mensaje de bienvenida
    print("Bienvenido a la práctica de Python")
    
    # Muestro el segundo mensaje con información adicional
    print("Práctica de administración de sistemas")
    
    # Imprimo otra línea de signos iguales como decoración
    print("=" * 50)

# Llamo a la función para ejecutar el código que contiene
mostrar_bienvenida()